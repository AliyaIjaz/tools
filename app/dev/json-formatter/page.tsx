'use client'

import { useState } from 'react'
import { CheckCircle, XCircle, Minimize2, Maximize2 } from 'lucide-react'
import ToolLayout from '@/components/ui/ToolLayout'
import CopyButton from '@/components/ui/CopyButton'
import SeoSection from '@/components/ui/SeoSection'

export default function JsonFormatterPage() {
  const [input, setInput] = useState('')
  const [output, setOutput] = useState('')
  const [error, setError] = useState('')
  const [status, setStatus] = useState<'idle' | 'valid' | 'invalid'>('idle')

  function format() {
    try {
      const parsed = JSON.parse(input)
      setOutput(JSON.stringify(parsed, null, 2))
      setError('')
      setStatus('valid')
    } catch (e) {
      setError((e as Error).message)
      setOutput('')
      setStatus('invalid')
    }
  }

  function minify() {
    try {
      const parsed = JSON.parse(input)
      setOutput(JSON.stringify(parsed))
      setError('')
      setStatus('valid')
    } catch (e) {
      setError((e as Error).message)
      setOutput('')
      setStatus('invalid')
    }
  }

  function validate() {
    try {
      JSON.parse(input)
      setError('')
      setStatus('valid')
    } catch (e) {
      setError((e as Error).message)
      setStatus('invalid')
    }
  }

  function syntaxHighlight(json: string) {
    return json.replace(
      /("(\\u[a-zA-Z0-9]{4}|\\[^u]|[^\\"])*"(\s*:)?|\b(true|false|null)\b|-?\d+(?:\.\d*)?(?:[eE][+\-]?\d+)?)/g,
      (match) => {
        let cls = 'text-sky-300'
        if (/^"/.test(match)) {
          cls = /:$/.test(match) ? 'text-violet-300' : 'text-emerald-300'
        } else if (/true|false/.test(match)) {
          cls = 'text-orange-300'
        } else if (/null/.test(match)) {
          cls = 'text-red-400'
        }
        return `<span class="${cls}">${match}</span>`
      }
    )
  }

  return (
    <ToolLayout
      toolId="json-formatter"
      title="JSON Formatter"
      description="Format, validate, and minify JSON with syntax highlighting"
      category="dev"
      iconName="Braces"
      showAllCategory
      seoContent={
        <SeoSection
          about={<>
            <p className="text-base leading-relaxed"><strong>JSON Formatter Online</strong> is a free browser-based tool that helps you <strong>format, beautify, validate, view, and minify JSON</strong> instantly. Whether you&apos;re working with API responses, configuration files, exported data, or application logs, this tool converts unreadable JSON into a clean, well-indented structure that&apos;s easier to read, edit, and debug.</p>
            <p className="text-base leading-relaxed">Simply paste your JSON into the editor to <strong>pretty print JSON</strong>, check for syntax errors, or compress it into a compact minified version for production use. The formatter uses standard <strong>2-space indentation</strong> to produce consistent and readable output while preserving the original data structure.</p>
            <p className="text-base leading-relaxed">This tool is designed for developers, testers, DevOps engineers, students, and anyone working with JSON data. It supports nested objects, arrays, and complex JSON documents, making it useful for everything from debugging REST API responses to reviewing configuration files.</p>
            <p className="text-base leading-relaxed">Because all formatting, validation, and minification happen entirely <strong>inside your browser</strong>, your JSON is never uploaded to a server. Your data remains private and secure throughout the entire process.</p>
          </>}
          useCases={[
            'Format minified API responses into a readable, properly indented structure.',
            'Validate JSON before committing configuration files to a repository.',
            'Find syntax errors by locating invalid JSON parsing issues.',
            'Minify JSON to reduce payload size for network requests and production deployments.',
            'Debug REST API and GraphQL responses during development.',
            'Review large JSON documents with nested objects and arrays.',
            'Clean up exported JSON data before sharing it with teammates.',
            'Verify JSON copied from online documentation or third-party services.',
            'Inspect webhook payloads during backend development.',
            'Edit package configuration files that use JSON.',
            'Prepare JSON examples for tutorials, blog posts, or documentation.',
            'Learn JSON formatting and understand complex data structures.',
            'Compare formatted JSON while reviewing code changes.',
            'Process JSON generated by JavaScript, Python, PHP, Java, Go, C#, or Node.js applications.',
            'Improve readability when working with logs, API testing tools, or database exports.',
          ]}
          faqs={[
            { q: 'What is a JSON Formatter?', a: 'A JSON Formatter (also called a JSON Beautifier or Pretty Print JSON tool) automatically adds indentation and line breaks to JSON, making it easier for humans to read without changing the actual data.' },
            { q: 'What is the difference between formatting and minifying JSON?', a: 'Formatting adds whitespace, indentation, and line breaks to improve readability. Minifying removes unnecessary whitespace to reduce file size while keeping the data exactly the same.' },
            { q: 'Can this tool validate my JSON?', a: 'Yes. The tool validates your JSON before formatting it. If the JSON contains syntax errors, you\'ll see an error message indicating where parsing failed.' },
            { q: 'Does formatting change my JSON data?', a: 'No. Formatting only changes whitespace and indentation. Keys, values, arrays, objects, numbers, strings, booleans, and null values remain unchanged.' },
            { q: 'What indentation style does the formatter use?', a: 'The formatter uses 2-space indentation, which is the most commonly used style for JSON and is widely adopted across modern development tools.' },
            { q: 'Can I format nested JSON?', a: 'Yes. The formatter fully supports deeply nested objects, arrays, and complex JSON structures while maintaining proper indentation throughout the document.' },
            { q: 'Does this tool support large JSON files?', a: 'Yes. Most JSON documents are formatted instantly. Extremely large files (hundreds of megabytes) may take longer depending on your browser\'s available memory and your device\'s performance.' },
            { q: 'Is my JSON uploaded to a server?', a: 'No. Everything runs locally in your browser using JavaScript\'s built-in JSON.parse() and JSON.stringify() methods. Your JSON never leaves your computer.' },
            { q: 'Can I use this tool offline?', a: 'If the webpage has already been loaded in your browser, the formatting and validation features continue to work locally because they do not require a server to process your JSON.' },
            { q: 'Does the formatter fix invalid JSON automatically?', a: 'No. The tool identifies syntax errors and reports them, but it does not automatically repair malformed JSON. This helps prevent unintended changes to your data.' },
            { q: 'Does this tool support JSON arrays?', a: 'Yes. You can format, validate, and minify JSON arrays, objects, nested structures, and combinations of both.' },
            { q: 'Can I use this tool for API responses?', a: 'Absolutely. It\'s ideal for formatting REST API and GraphQL responses from services like Postman, browser developer tools, or backend applications, making the data much easier to inspect and debug.' },
            { q: 'Which programming languages use JSON?', a: 'JSON is widely used with JavaScript, TypeScript, Node.js, Python, PHP, Java, C#, Go, Ruby, Kotlin, Swift, Rust, and many other programming languages for data exchange and configuration.' },
            { q: 'Is there a file size limit?', a: 'There is no built-in limit imposed by the tool itself. The maximum size depends on your browser\'s available memory and your device\'s hardware resources.' },
            { q: 'Why should I format JSON?', a: 'Formatting JSON improves readability, makes debugging easier, simplifies collaboration, reduces mistakes when editing, and helps you better understand complex data structures without altering the underlying data.' },
          ]}
        />
      }
    >
      <div className="space-y-5">
        {/* Input */}
        <div
          className="rounded-xl p-4"
          style={{ background: 'var(--surface)', border: '2px solid var(--border-dev-idle)' }}
        >
          <label className="block text-sm font-semibold mb-3" style={{ color: 'rgba(255,255,255,0.75)' }}>
            Input JSON
          </label>
          <textarea
            value={input}
            onChange={(e) => setInput(e.target.value)}
            placeholder='{"hello": "world"}'
            rows={12}
            className="w-full resize-y rounded-lg px-3 py-3 text-sm outline-none transition-all duration-150 placeholder:text-white/50"
            style={{
              background: 'rgba(0,0,0,0.35)',
              border: '2px solid var(--border-dev)',
              color: 'rgba(255,255,255,0.92)',
              fontFamily: 'var(--font-geist-mono), monospace',
              lineHeight: '1.65',
            }}
            onFocus={(e) => { e.currentTarget.style.borderColor = 'var(--color-dev)' }}
            onBlur={(e) => { e.currentTarget.style.borderColor = 'var(--border-dev-idle)' }}
          />
        </div>

        {/* Actions */}
        <div className="flex flex-wrap items-center gap-2">
          <button
            onClick={format}
            className="flex items-center gap-1.5 px-5 py-2.5 rounded-lg text-sm font-semibold transition-all"
            style={{ background: 'var(--color-dev)', color: '#fff' }}
          >
            <Maximize2 size={14} />
            Format
          </button>
          <button
            onClick={minify}
            className="flex items-center gap-1.5 px-5 py-2.5 rounded-lg text-sm font-semibold transition-all"
            style={{ background: 'rgba(255,255,255,0.08)', border: '1px solid rgba(255,255,255,0.15)', color: 'rgba(255,255,255,0.85)' }}
          >
            <Minimize2 size={14} />
            Minify
          </button>
          <button
            onClick={validate}
            className="flex items-center gap-1.5 px-5 py-2.5 rounded-lg text-sm font-semibold transition-all"
            style={{ background: 'rgba(255,255,255,0.08)', border: '1px solid rgba(255,255,255,0.15)', color: 'rgba(255,255,255,0.85)' }}
          >
            Validate
          </button>

          {status === 'valid' && (
            <div className="flex items-center gap-1.5 text-sm font-medium text-emerald-400">
              <CheckCircle size={15} /> Valid JSON
            </div>
          )}
          {status === 'invalid' && (
            <div className="flex items-center gap-1.5 text-sm font-medium text-red-400">
              <XCircle size={15} /> Invalid JSON
            </div>
          )}
        </div>

        {/* Error */}
        {error && (
          <div
            className="rounded-lg px-4 py-3 text-sm font-mono leading-relaxed"
            style={{ background: 'rgba(239,68,68,0.12)', border: '1px solid rgba(239,68,68,0.35)', color: '#fca5a5' }}
          >
            {error}
          </div>
        )}

        {/* Output */}
        {output && (
          <div
            className="rounded-xl p-4"
            style={{ background: 'var(--surface)', border: '2px solid var(--border-dev-idle)' }}
          >
            <div className="flex items-center justify-between mb-3">
              <label className="text-sm font-semibold" style={{ color: 'rgba(255,255,255,0.75)' }}>Output</label>
              <CopyButton text={output} />
            </div>
            <pre
              className="rounded-lg px-3 py-3 text-sm overflow-auto leading-relaxed"
              style={{
                background: 'rgba(0,0,0,0.35)',
                border: '2px solid var(--border-dev-idle)',
                fontFamily: 'var(--font-geist-mono), monospace',
                color: 'rgba(255,255,255,0.88)',
                maxHeight: '480px',
              }}
              dangerouslySetInnerHTML={{ __html: syntaxHighlight(output) }}
            />
          </div>
        )}
      </div>
    </ToolLayout>
  )
}
